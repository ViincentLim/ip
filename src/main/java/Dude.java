import java.io.IOException;
import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.Scanner;
import java.util.stream.IntStream;
import java.util.stream.Stream;

import exception.UsageException;
import storage.Storage;
import task.Deadline;
import task.Event;
import task.Task;
import task.TaskDate;
import task.Todo;

/**
 * Runs the DUDE command-line application.
 */
public class Dude {
    private static final String RED = "\u001B[31m";
    private static final String RESET = "\u001B[0m";
    private static final String TASK_USAGE = "Usage: todo <task details> | deadline <description> /by"
            + " <yyyy-MM-dd [HHmm]> | event <description> /from <yyyy-MM-dd [HHmm]>"
            + " /to <yyyy-MM-dd [HHmm]> | on <yyyy-MM-dd>";

    /**
     * Creates a DUDE application instance.
     */
    public Dude() {
    }

    /**
     * Starts the application and processes commands entered by the user.
     *
     * @param args Command-line arguments, which are not used by the application.
     */
    static void main(String[] args) {
        // Banner generated by ChatGPT but edited manually to align better
        String banner = "██████╗  ██╗   ██╗ ██████╗  ███████╗\n"
                + "██╔══██╗ ██║   ██║ ██╔══██╗ ██╔════╝\n"
                + "██║  ██║ ██║   ██║ ██║  ██║ █████╗\n"
                + "██║  ██║ ██║   ██║ ██║  ██║ ██╔══╝\n"
                + "██████╔╝ ╚██████╔╝╚██████╔╝ "
                + "███████╗\n"
                + "╚═════╝   ╚═════╝ ╚══════╝  ╚══════╝";

        int width = getTerminalWidth();
        String border = "─".repeat(width);

        printBox(border, banner, "Hello! I'm DUDE.",
                "Dates can be represented in this format: yyyy-MM-dd.",
                "To include a time, use this format: yyyy-MM-dd HHmm.",
                "What can I do for you?");

        Storage storage = new Storage();
        ArrayList<Task> tasks = loadTasks(border, storage);

        try(Scanner scanner = new Scanner(System.in)) {
            onUpdate(scanner, border, tasks, storage);
        }
    }

    /**
     * Processes commands until the user enters the exit command or input ends.
     */
    private static void onUpdate(Scanner scanner, String border, ArrayList<Task> tasks,
            Storage storage) {
        while (scanner.hasNextLine()) {
            String input = scanner.nextLine();
            if (input.isBlank()) {
                continue;
            }
            String[] commandParts = input.trim().split("\\s+", 2);
            String action = commandParts[0];
            String argument = commandParts.length > 1 ? commandParts[1] : null;

            try {
                Command command = Command.parse(action);
                if (command == null) {
                    throw new UsageException(action, "command", action,
                            "todo, deadline, event, or on", TASK_USAGE, "<task type>");
                }

                switch (command) {
                    case BYE:
                        printBox(border, "Bye. Hope to see you again soon!");
                        return;
                    case LIST:
                        printTaskList(border, tasks);
                        break;
                    case ON:
                        printTasksOnDate(border, tasks, argument);
                        break;
                    case MARK, UNMARK:
                        updateTask(border, tasks, command, argument);
                        saveTasks(border, tasks, storage);
                        break;
                    case DELETE:
                        deleteTask(border, tasks, argument);
                        saveTasks(border, tasks, storage);
                        break;
                    case TODO, DEADLINE, EVENT:
                        addTask(border, tasks, command, argument);
                        saveTasks(border, tasks, storage);
                        break;
                }
            } catch (UsageException e) {
                printError(border, e);
            }
        }
    }

    /**
     * Returns tasks loaded from disk, or an empty list when loading fails.
     */
    private static ArrayList<Task> loadTasks(String border, Storage storage) {
        try {
            return storage.loadTasks();
        } catch (IOException exception) {
            printBox(border,
                    "Error: unable to load tasks from disk.",
                    "Starting with an empty task list.");
            return new ArrayList<>();
        }
    }

    /**
     * Saves the current tasks and reports a failure without stopping the application.
     */
    private static void saveTasks(String border, ArrayList<Task> tasks, Storage storage) {
        try {
            storage.saveTasks(tasks);
        } catch (IOException exception) {
            printBox(border,
                    "Error: unable to save tasks to disk.",
                    "The change remains in memory for this session.");
        }
    }

    /**
     * Marks or unmarks the task identified by a one-based task number.
     */
    private static void updateTask(String border, ArrayList<Task> tasks,
            Command command, String argument) throws UsageException {
        int taskIndex = parseTaskIndex(command, tasks, argument);

        Task task = tasks.get(taskIndex);
        String[] messageLines = switch (command) {
            case MARK -> {
                task.markAsDone();
                yield new String[] {
                        "Nice! I've marked this task as done:",
                        "  " + task
                };
            }
            case UNMARK -> {
                task.markAsNotDone();
                yield new String[] {
                        "OK, I've marked this task as not done yet:",
                        "  " + task
                };
            }
            default -> throw new IllegalArgumentException("Unsupported task action: " + command);
        };
        printBox(border, messageLines);
    }

    /**
     * Removes the task identified by a one-based task number.
     */
    private static void deleteTask(String border, ArrayList<Task> tasks, String argument)
            throws UsageException {
        int taskIndex = parseTaskIndex(Command.DELETE, tasks, argument);
        Task task = tasks.remove(taskIndex);
        printBox(border,
                "Noted. I've removed this task:",
                "  " + task,
                String.format("Now you have %d tasks in the list.", tasks.size()));
    }

    /**
     * Returns the zero-based index represented by a valid one-based task number.
     */
    private static int parseTaskIndex(Command command, ArrayList<Task> tasks, String argument)
            throws UsageException {
        if (argument == null || argument.isBlank()) {
            throw usageError(command, "task number", "<missing>", "an integer", "<task number>");
        }

        int taskNumber;
        try {
            taskNumber = Integer.parseInt(argument);
        } catch (NumberFormatException e) {
            throw usageError(command, "task number", argument, "an integer", "<task number>", e);
        }

        int taskIndex = taskNumber - 1;
        if (taskIndex < 0 || taskIndex >= tasks.size()) {
            throw usageError(command, "task number", argument,
                    "an existing task number", "<task number>");
        }
        return taskIndex;
    }

    /**
     * Creates and stores a task from a typed task command.
     */
    private static void addTask(String border, ArrayList<Task> tasks,
            Command command, String argument) throws UsageException {
        Task task = switch (command) {
            case TODO -> Todo.fromInput(argument);
            case DEADLINE -> Deadline.fromInput(argument);
            case EVENT -> Event.fromInput(argument);
            default -> throw new IllegalArgumentException("Unsupported task type: " + command);
        };

        tasks.add(task);
        printBox(border,
                "Got it. I've added this task:",
                "  " + task,
                String.format("Now you have %d tasks in the list.", tasks.size()));
    }

    /**
     * Prints deadlines and events that occur on the requested date.
     */
    private static void printTasksOnDate(String border, ArrayList<Task> tasks, String argument)
            throws UsageException {
        if (argument == null || argument.isBlank()) {
            throw usageError(Command.ON, "date", "<missing>", "yyyy-MM-dd", "<yyyy-MM-dd>");
        }

        LocalDate date;
        try {
            date = TaskDate.parseDate(argument);
        } catch (DateTimeParseException exception) {
            throw usageError(Command.ON, "date", argument, "yyyy-MM-dd", "<yyyy-MM-dd>", exception);
        }

        String[] matchingTasks = Stream.concat(
                        Stream.of(String.format("Tasks occurring on %s:", date)),
                        IntStream.range(0, tasks.size())
                                .filter(index -> occursOn(tasks.get(index), date))
                                .mapToObj(index -> String.format("%d.%s", index + 1, tasks.get(index))))
                .toArray(String[]::new);
        printBox(border, matchingTasks);
    }

    /**
     * Returns whether a task occurs on a date.
     */
    private static boolean occursOn(Task task, LocalDate date) {
        if (task instanceof Deadline deadline) {
            return deadline.getBy().occursOn(date);
        }
        return task instanceof Event event && event.occursOn(date);
    }

    /**
     * Returns a usage exception for an invalid command field.
     */
    private static UsageException usageError(Command command, String fieldName,
            String actualValue, String expectedType,
            String usageToken) {
        return new UsageException(command.getWord(), fieldName, actualValue, expectedType,
                command.getUsageMessage(), usageToken);
    }

    /**
     * Returns a usage exception for an invalid command field and its cause.
     */
    private static UsageException usageError(Command command, String fieldName,
            String actualValue, String expectedType,
            String usageToken, Throwable cause) {
        return new UsageException(command.getWord(), fieldName, actualValue, expectedType,
                command.getUsageMessage(), usageToken, cause);
    }

    /**
     * Prints a customized error and the usage message for an invalid command.
     */
    private static void printError(String border, UsageException e) {
        String usage = e.getUsageMessage().replace(
                e.getUsageToken(), RED + e.getUsageToken() + RESET);
        String actualValue = formatActualValue(e.getActualValue());

        if ("command".equals(e.getFieldName())) {
            printBox(border,
                    String.format("Error: invalid command %s.", actualValue),
                    String.format("Expected: %s.", e.getExpectedType()),
                    usage);
            return;
        }

        printBox(border,
                String.format("Error: invalid %s %s for %s.", e.getFieldName(),
                        actualValue, e.getAction()),
                String.format("Expected: %s.", e.getExpectedType()),
                usage);
    }

    /**
     * Prints all stored tasks with their one-based positions.
     */
    private static void printTaskList(String border, ArrayList<Task> tasks) {
        String[] taskLines = Stream.concat(
                        Stream.of("Here are the tasks in your list:"),
                        IntStream.range(0, tasks.size())
                                .mapToObj(i -> String.format("%d.%s", i + 1, tasks.get(i))))
                .toArray(String[]::new);
        printBox(border, taskLines);
    }

    /**
     * Returns the terminal width, or a default width when it cannot be determined.
     */
    private static int getTerminalWidth() {
        try {
            var console = System.console();
            if (console != null) {
                var method = console.getClass().getMethod("getWidth");
                return (int) method.invoke(console);
            }
        } catch (Exception ignored) {
        }
        return 60;
    }

    /**
     * Prints the supplied lines between two borders.
     */
    private static void printBox(String border, String... lines) {
        System.out.println(border);
        for (String line : lines) {
            for (String part : line.split("\n")) {
                System.out.println(padRight(part, border.length()));
            }
        }
        System.out.println(border);
    }

    /**
     * Returns the supplied text padded with spaces to the requested length.
     */
    private static String padRight(String s, int length) {
        return s.length() >= length ? s : s + " ".repeat(length - s.length());
    }

    /**
     * Returns an actual input value formatted for display in an error message.
     */
    private static String formatActualValue(String actualValue) {
        if (actualValue == null || actualValue.equals("<missing>")) {
            return "<missing>";
        }
        return String.format("\"%s\"", actualValue);
    }
}
